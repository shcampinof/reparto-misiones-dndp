CREATE TABLE SIGIP_COBERTURA_TERRITORIAL (
  COBERTURA_TERRITORIAL_ID VARCHAR2(36 CHAR) NOT NULL, AREA_ID VARCHAR2(36 CHAR) NOT NULL,
  ESPECIALIDAD_SERVICIO_ID VARCHAR2(36 CHAR) NOT NULL, USUARIO_ID VARCHAR2(36 CHAR) NOT NULL,
  REGIONAL_ID VARCHAR2(36 CHAR), GEOGRAFIA_ID VARCHAR2(36 CHAR), INCLUIDA CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
  PRIORIDAD NUMBER(9), ACTIVO CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
  VIGENTE_DESDE TIMESTAMP(6) WITH TIME ZONE NOT NULL, VIGENTE_HASTA TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT PK_SIGIP_COB_TERR PRIMARY KEY (COBERTURA_TERRITORIAL_ID), CONSTRAINT FK_SIGIP_CT_AREA FOREIGN KEY (AREA_ID) REFERENCES SIGIP_AREA (AREA_ID),
  CONSTRAINT FK_SIGIP_CT_ESP FOREIGN KEY (ESPECIALIDAD_SERVICIO_ID) REFERENCES SIGIP_ESPECIALIDAD_SERVICIO (ESPECIALIDAD_SERVICIO_ID),
  CONSTRAINT FK_SIGIP_CT_USR FOREIGN KEY (USUARIO_ID) REFERENCES SIGIP_USUARIO (USUARIO_ID), CONSTRAINT FK_SIGIP_CT_REG FOREIGN KEY (REGIONAL_ID) REFERENCES SIGIP_REGIONAL (REGIONAL_ID),
  CONSTRAINT FK_SIGIP_CT_GEO FOREIGN KEY (GEOGRAFIA_ID) REFERENCES SIGIP_GEOGRAFIA (GEOGRAFIA_ID),
  CONSTRAINT CK_SIGIP_CT_DEST CHECK (REGIONAL_ID IS NOT NULL OR GEOGRAFIA_ID IS NOT NULL), CONSTRAINT CK_SIGIP_CT_INC CHECK (INCLUIDA IN ('S','N')),
  CONSTRAINT CK_SIGIP_CT_ACT CHECK (ACTIVO IN ('S','N')), CONSTRAINT CK_SIGIP_CT_VIG CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA > VIGENTE_DESDE)
);

