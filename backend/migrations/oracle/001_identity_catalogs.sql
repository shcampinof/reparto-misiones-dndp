CREATE TABLE SIGIP_AREA (
  AREA_ID VARCHAR2(36 CHAR) NOT NULL, CODIGO VARCHAR2(50 CHAR) NOT NULL,
  NOMBRE VARCHAR2(200 CHAR) NOT NULL, ACTIVO CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
  VIGENTE_DESDE TIMESTAMP(6) WITH TIME ZONE NOT NULL, VIGENTE_HASTA TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT PK_SIGIP_AREA PRIMARY KEY (AREA_ID), CONSTRAINT UK_SIGIP_AREA_COD_VIG UNIQUE (CODIGO, VIGENTE_DESDE),
  CONSTRAINT CK_SIGIP_AREA_ACT CHECK (ACTIVO IN ('S','N')), CONSTRAINT CK_SIGIP_AREA_VIG CHECK (VIGENTE_HASTA IS NULL OR VIGENTE_HASTA > VIGENTE_DESDE)
);

