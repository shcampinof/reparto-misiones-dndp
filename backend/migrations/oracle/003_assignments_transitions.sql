CREATE TABLE SIGIP_ASIGNACION (
  ASIGNACION_ID VARCHAR2(36 CHAR) NOT NULL, ITEM_SOLICITUD_ID VARCHAR2(36 CHAR) NOT NULL,
  DECISION_ASIGNACION_ID VARCHAR2(36 CHAR), RESPONSABLE_USUARIO_ID VARCHAR2(36 CHAR) NOT NULL,
  TIPO_ASIGNACION VARCHAR2(40 CHAR) NOT NULL, VERSION_POLITICA VARCHAR2(100 CHAR) NOT NULL,
  ES_VIGENTE CHAR(1 CHAR) DEFAULT 'S' NOT NULL, VERSION NUMBER(18) DEFAULT 1 NOT NULL,
  ASIGNADO_EN TIMESTAMP(6) WITH TIME ZONE NOT NULL, FINALIZADO_EN TIMESTAMP(6) WITH TIME ZONE,
  MOTIVO VARCHAR2(1000 CHAR) NOT NULL, AUTORIZADO_POR VARCHAR2(36 CHAR),
  CONSTRAINT PK_SIGIP_ASIGNACION PRIMARY KEY (ASIGNACION_ID), CONSTRAINT FK_SIGIP_ASG_ITEM FOREIGN KEY (ITEM_SOLICITUD_ID) REFERENCES SIGIP_ITEM_SOLICITUD (ITEM_SOLICITUD_ID),
  CONSTRAINT FK_SIGIP_ASG_DEC FOREIGN KEY (DECISION_ASIGNACION_ID) REFERENCES SIGIP_DECISION_ASIGNACION (DECISION_ASIGNACION_ID),
  CONSTRAINT FK_SIGIP_ASG_RESP FOREIGN KEY (RESPONSABLE_USUARIO_ID) REFERENCES SIGIP_USUARIO (USUARIO_ID), CONSTRAINT FK_SIGIP_ASG_AUT FOREIGN KEY (AUTORIZADO_POR) REFERENCES SIGIP_USUARIO (USUARIO_ID),
  CONSTRAINT CK_SIGIP_ASG_VIG CHECK (ES_VIGENTE IN ('S','N')), CONSTRAINT CK_SIGIP_ASG_VER CHECK (VERSION > 0),
  CONSTRAINT CK_SIGIP_ASG_FIN CHECK ((ES_VIGENTE = 'S' AND FINALIZADO_EN IS NULL) OR ES_VIGENTE = 'N')
);

CREATE UNIQUE INDEX UX_SIGIP_ASG_VIGENTE ON SIGIP_ASIGNACION (CASE WHEN ES_VIGENTE = 'S' THEN ITEM_SOLICITUD_ID END);

