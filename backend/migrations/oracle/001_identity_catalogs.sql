  ACTIVO CHAR(1 CHAR) DEFAULT 'S' NOT NULL, VIGENTE_DESDE TIMESTAMP(6) WITH TIME ZONE NOT NULL, VIGENTE_HASTA TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT PK_SIGIP_GEOGRAFIA PRIMARY KEY (GEOGRAFIA_ID), CONSTRAINT FK_SIGIP_GEO_PADRE FOREIGN KEY (GEOGRAFIA_PADRE_ID) REFERENCES SIGIP_GEOGRAFIA (GEOGRAFIA_ID),
