CREATE TABLE SIGIP_NOVEDAD (
  NOVEDAD_ID VARCHAR2(36 CHAR) NOT NULL, USUARIO_ID VARCHAR2(36 CHAR) NOT NULL, TIPO_NOVEDAD_CODIGO VARCHAR2(80 CHAR) NOT NULL,
  AUTORIZADO_POR VARCHAR2(36 CHAR) NOT NULL, BLOQUEA_NUEVAS_ASIGNACIONES CHAR(1 CHAR) NOT NULL, MOTIVO VARCHAR2(1000 CHAR) NOT NULL,
