  CODIGO_REGLA VARCHAR2(120 CHAR) NOT NULL, EXPLICACION VARCHAR2(1000 CHAR) NOT NULL,
  CONSTRAINT PK_SIGIP_EXC_CAND PRIMARY KEY (EXCLUSION_CANDIDATO_ID), CONSTRAINT FK_SIGIP_EC_CAND FOREIGN KEY (CANDIDATO_DECISION_ID) REFERENCES SIGIP_CANDIDATO_DECISION (CANDIDATO_DECISION_ID),
  CONSTRAINT UK_SIGIP_EC_REGLA UNIQUE (CANDIDATO_DECISION_ID, CODIGO_REGLA)
