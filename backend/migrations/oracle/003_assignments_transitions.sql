  CONSTRAINT PK_SIGIP_CAND_DEC PRIMARY KEY (CANDIDATO_DECISION_ID), CONSTRAINT FK_SIGIP_CD_DEC FOREIGN KEY (DECISION_ASIGNACION_ID) REFERENCES SIGIP_DECISION_ASIGNACION (DECISION_ASIGNACION_ID),
  CONSTRAINT FK_SIGIP_CD_USR FOREIGN KEY (USUARIO_ID) REFERENCES SIGIP_USUARIO (USUARIO_ID), CONSTRAINT UK_SIGIP_CD_USR UNIQUE (DECISION_ASIGNACION_ID, USUARIO_ID),
